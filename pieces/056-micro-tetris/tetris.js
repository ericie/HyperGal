(() => {
  const canvas = document.querySelector('canvas');
  const context = canvas.getContext('2d', { alpha: false });
  const recipes = window.MICRO_TETRIS_RECIPES;
  const motion = matchMedia('(prefers-reduced-motion: reduce)');
  const colors = ['#090b10', '#76c9cd', '#d6bb6a', '#af93d4', '#83b995', '#cf7d8a', '#7598cf', '#cf9b74'];
  const colorBytes = colors.map(color => [1, 3, 5].map(i => parseInt(color.slice(i, i + 2), 16)));
  let width, height, board, lanes, image, pixels;
  let active = [], hot = false, paused = motion.matches, last = null, credit = 0, drawn = 0;
  let cleared = 0, cycles = 0;

  const randomRecipe = () => recipes[Math.floor(Math.random() * recipes.length)];
  function nextPiece(lane) {
    if (lane.width < 4) {
      return { color: 1, cells: [[0,0],[0,1],[0,2],[0,3]], x: lane.cursor, y: 0 };
    }
    return lane.recipe[lane.cursor];
  }
  function target(lane, piece) {
    return piece.cells.map(([x, y]) => [lane.x + piece.x + x, lane.base + piece.y + y]);
  }
  function lock(lane, piece) {
    const cells = target(lane, piece);
    // Packing recipes were generated by dropping real tetrominoes under
    // gravity, and each four-piece recipe leaves a flat 4 × 4 surface.
    for (const [x, y] of cells) {
      if (y < 0 || y >= height || board[y * width + x]) throw new Error('Invalid tetromino placement');
      board[y * width + x] = piece.color;
    }
    lane.cursor++;
    if (lane.cursor === (lane.width < 4 ? lane.width : 4)) {
      lane.base += 4;
      lane.cursor = 0;
      lane.recipe = randomRecipe();
    }
    lane.busy = false;
  }
  function clearRows() {
    // Completed packing bands below every lane are guaranteed full. Waiting
    // for a band boundary keeps in-flight targets intact when rows collapse.
    const count = Math.min(...lanes.map(lane => lane.base));
    if (!count) return;
    board.copyWithin(0, count * width);
    board.fill(0, (height - count) * width);
    for (const lane of lanes) lane.base -= count;
    cleared += count;
  }
  function reset() {
    width = Math.max(1, Math.floor(innerWidth));
    height = Math.max(16, Math.floor(innerHeight));
    canvas.width = width;
    canvas.height = height;
    board = new Uint8Array(width * height);
    image = context.createImageData(width, height);
    pixels = new Uint32Array(image.data.buffer);
    lanes = [];
    active = [];
    hot = false; cleared = 0; cycles = 0; credit = 0;
    for (let x = 0; x < width; x += 4) {
      const lane = { x, width: Math.min(4, width - x), base: 0, cursor: 0, recipe: randomRecipe(), busy: false, favored: Math.random() < .72 };
      lanes.push(lane);
      // Deep open wells and incomplete bands, all seeded with legal drops.
      const targetHeight = Math.max(4, Math.floor(height * (.14 + Math.random() * .30) / 4) * 4);
      while (lane.base < targetHeight) lock(lane, nextPiece(lane));
      const extra = Math.floor(Math.random() * (lane.width < 4 ? lane.width : 4));
      for (let i = 0; i < extra; i++) lock(lane, nextPiece(lane));
    }
    render();
  }
  function chooseLane() {
    if (hot) {
      let best = null;
      const floor = Math.min(...lanes.map(lane => lane.base));
      for (const lane of lanes) {
        if (lane.busy || lane.base > floor + 4 || lane.base + 4 > height - 4) continue;
        if (!best || lane.base < best.base || (lane.base === best.base && lane.cursor > best.cursor)) best = lane;
      }
      return best;
    }
    for (let i = 0; i < 24; i++) {
      const lane = lanes[Math.floor(Math.random() * lanes.length)];
      if (!lane.busy && lane.base + 4 < height * .76 && (lane.favored || Math.random() < .035)) return lane;
    }
    return null;
  }
  function advance(seconds) {
    for (let i = active.length - 1; i >= 0; i--) {
      const falling = active[i];
      falling.elapsed += seconds;
      if (falling.elapsed >= falling.duration) {
        lock(falling.lane, falling.piece);
        active.splice(i, 1);
      }
    }
    clearRows();
    const peak = Math.max(...lanes.map(lane => lane.base + 4));
    if (!hot && peak >= height * .70) hot = true;
    if (hot && peak < height * .27) {
      hot = false; cycles++;
      for (const lane of lanes) lane.favored = Math.random() < .72;
    }
    // Throughput scales with window area. Hundreds of four-pixel pieces can
    // fall concurrently, making a thousand-column game watchable in real time.
    credit = Math.min(credit + seconds * width * height / (hot ? 135 : 420), lanes.length);
    while (credit >= 1) {
      const lane = chooseLane();
      if (!lane) { credit = 0; break; }
      const piece = nextPiece(lane);
      lane.busy = true;
      active.push({ lane, piece, elapsed: 0, duration: hot ? .055 + Math.random() * .09 : .16 + Math.random() * .30 });
      credit--;
    }
  }
  // Pack RGBA using the platform's byte order rather than assuming it.
  const packed = colorBytes.map(([r,g,b]) => new Uint32Array(new Uint8Array([r,g,b,255]).buffer)[0]);
  function render() {
    for (let i = 0; i < board.length; i++) pixels[(height - 1 - Math.floor(i / width)) * width + i % width] = packed[board[i]];
    context.putImageData(image, 0, 0);
    for (const falling of active) {
      const t = Math.min(1, falling.elapsed / falling.duration);
      const cells = target(falling.lane, falling.piece);
      const start = height + 4;
      const offset = Math.round((start - falling.lane.base) * (1 - t));
      context.fillStyle = colors[falling.piece.color];
      for (const [x, y] of cells) context.fillRect(x, height - 1 - y - offset, 1, 1);
    }
    canvas.dataset.phase = hot ? 'hot-streak' : 'building';
    canvas.dataset.cleared = cleared;
    canvas.dataset.cycles = cycles;
    canvas.dataset.peak = Math.max(...lanes.map(lane => lane.base + 4));
  }
  function frame(now) {
    const seconds = last === null ? 0 : Math.min(.05, (now - last) / 1000);
    last = now;
    if (!paused && !document.hidden) advance(seconds);
    if (now - drawn > 1000 / 30 && !paused) { render(); drawn = now; }
    requestAnimationFrame(frame);
  }
  function toggle() { paused = !paused; canvas.setAttribute('aria-pressed', String(paused)); }
  canvas.addEventListener('click', toggle);
  addEventListener('keydown', event => {
    if (event.code === 'Space') { event.preventDefault(); toggle(); }
    if (event.key.toLowerCase() === 'r') reset();
  });
  let resizing;
  addEventListener('resize', () => { clearTimeout(resizing); resizing = setTimeout(reset, 120); });
  motion.addEventListener('change', event => { paused = event.matches; canvas.setAttribute('aria-pressed', String(paused)); });
  canvas.setAttribute('aria-pressed', String(paused));
  reset();
  requestAnimationFrame(frame);
})();
