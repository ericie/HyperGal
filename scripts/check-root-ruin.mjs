import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url);
const Matter=require('../pieces/061-root-ruin/vendor/matter-0.20.0.min.js');
let randomSeed=257;
const math=Object.create(Math);math.random=()=>{randomSeed=(randomSeed*1664525+1013904223)>>>0;return randomSeed/4294967296;};
const canvas={getContext:()=>new Proxy({}, {get:()=>()=>{}})};
const sandbox={Matter,Math:math,console,document:{querySelector:()=>canvas,addEventListener(){}},innerWidth:1200,innerHeight:850,devicePixelRatio:1,matchMedia:()=>({matches:false}),addEventListener(){},requestAnimationFrame(){}};
const source=readFileSync(new URL('../pieces/061-root-ruin/sketch.js',import.meta.url),'utf8').replace('resize();reset();requestAnimationFrame(frame);','resize();reset();globalThis.sim={step,reset,fracture,makeRock,addPlant,plantBase,plantTop,plantAngle,checkBurials,local,world,get state(){return {engine,rocks,plants,seeds,fruits,fractures}}};');
vm.runInNewContext(source,sandbox);const sim=sandbox.sim;
const advance=seconds=>{for(let i=0;i<seconds*120;i++)sim.step(1/120);};
const snapshot=sim.state.rocks.map(r=>({...r.body.position}));advance(10);
sim.state.rocks.forEach((r,i)=>assert.deepEqual({...r.body.position},snapshot[i],'Intact terrain must remain rigid'));
const plant=sim.state.plants[0],parent=plant.rock,area=parent.body.area,base=sim.plantBase(plant),angle=sim.plantAngle(plant),before=new Set(sim.state.rocks);
assert.ok(sim.fracture(parent),'Rooted monolith must split');
const children=sim.state.rocks.filter(r=>!before.has(r));
assert.ok(children.length>=3);assert.ok(Math.abs(children.reduce((sum,r)=>sum+r.body.area,0)-area)<.001,'Fracture must preserve polygon area');
assert.ok(Math.hypot(sim.plantBase(plant).x-base.x,sim.plantBase(plant).y-base.y)<1e-6,'Fracture must preserve the root attachment');
assert.ok(Math.abs(sim.plantAngle(plant)-angle)<1e-6,'Fracture must preserve plant orientation');
const anchor={...plant.anchor},body=plant.rock.body;
Matter.Body.setAngle(body,.7);Matter.Body.translate(body,{x:13,y:-25});
assert.deepEqual({...plant.anchor},anchor,'Root anchor must not slide');
assert.ok(Math.abs(sim.plantAngle(plant)-angle-.7)<1e-6,'Plant must rotate with its rock');
sim.reset();const crushed=sim.state.plants[0],top=sim.plantTop(crushed);
sim.makeRock([{x:top.x-15,y:top.y-15},{x:top.x+15,y:top.y-15},{x:top.x+15,y:top.y+15},{x:top.x-15,y:top.y+15}]);sim.checkBurials();assert.ok(crushed.dead,'Overlapping rock must crush a plant');advance(12);assert.ok(sim.state.plants.includes(crushed),'A dead stem must linger long enough to register the loss');
// Two physical rocks must stack, not pass through one another or vanish.
sim.reset();for(const r of sim.state.rocks)Matter.Composite.remove(sim.state.engine.world,r.body);sim.state.rocks.splice(0);sim.state.plants.splice(0);
const square=(x,y)=>sim.makeRock([{x:x-30,y:y-30},{x:x+30,y:y-30},{x:x+30,y:y+30},{x:x-30,y:y+30}]);
const lower=square(600,705),upper=square(603,620);advance(8);
assert.ok(upper.body.position.y<lower.body.position.y-55,'Rocks must support a stable pile');
assert.ok(lower.body.bounds.max.y<736,'Rock must rest on the floor');
assert.equal(sim.state.rocks.length,2,'Rubble must not disappear');
sim.reset();advance(240);
assert.ok(sim.state.fractures>0,'Natural roots must fracture rock');
assert.ok(sim.state.rocks.every(r=>Number.isFinite(r.body.position.x)&&Number.isFinite(r.body.position.y)),'Physics must remain finite');
console.log('PASS: rigid terrain, conserved fracture area, fixed rotating plant anchors, crushing, colliding rubble piles, and 240 seconds of natural growth.');
console.log({rocks:sim.state.rocks.length,fractures:sim.state.fractures,plants:sim.state.plants.length,seeds:sim.state.seeds.length});
